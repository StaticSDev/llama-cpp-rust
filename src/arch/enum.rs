impl Arch {
    /// Architecture name as stored in `general.architecture`.
    pub fn name(self) -> &'static str {
        for (arch, name) in ARCH_NAMES {
            if *arch == self {
                return *name;
            }
        }
        "unknown"
    }

    /// Reverse lookup of a GGUF architecture string.
    pub fn from_string(name: &str) -> Self {
        for (arch, arch_name) in ARCH_NAMES {
            if *arch_name == name {
                return *arch;
            }
        }
        Arch::Unknown
    }
}

/// All architectures.
pub fn arch_all() -> Vec<Arch> {
    ALL_ARCHES.to_vec()
}

/// Architecture name (alias of `Arch::name`).
pub fn arch_name(arch: Arch) -> &'static str { arch.name() }

/// Architecture from string (alias of `Arch::from_string`).
pub fn arch_from_string(name: &str) -> Arch { Arch::from_string(name) }

/// Alias of `arch_all`.
pub fn llama_arch_all() -> Vec<Arch> { arch_all() }

/// Alias of `arch_name`.
pub fn llama_arch_name(arch: Arch) -> &'static str { arch_name(arch) }

/// Alias of `arch_from_string`.
pub fn llama_arch_from_string(name: &str) -> Arch { arch_from_string(name) }
