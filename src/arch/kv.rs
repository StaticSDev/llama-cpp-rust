fn format_tensor(pattern: &str, bid: i32, xid: i32) -> String {
    let mut out = String::with_capacity(pattern.len());
    let mut rest = pattern;
    for arg in [bid, xid] {
        if let Some(pos) = rest.find("%d") {
            out.push_str(&rest[..pos]);
            out.push_str(&arg.to_string());
            rest = &rest[pos + 2..];
        }
    }
    out.push_str(rest);
    out
}

/// Helper for GGUF metadata keys: `LLM_KV(arch, suffix)(key)`.
pub struct LlmKv {
    pub arch: Arch,
    pub suffix: Option<String>,
}

impl LlmKv {
    pub fn new(arch: Arch, suffix: Option<&str>) -> Self {
        Self { arch, suffix: suffix.map(str::to_owned) }
    }

    /// Resolve a key, appending the optional suffix.
    pub fn key(&self, kv: Kv) -> String {
        let mut name = kv.format(self.arch);
        if let Some(suffix) = &self.suffix {
            name.push('.');
            name.push_str(suffix);
        }
        name
    }
}

/// Helper for GGUF tensor names: `LLM_TN(arch)(tensor, suffix, bid, xid)`.
pub struct LlmTn {
    pub arch: Arch,
}

impl LlmTn {
    pub fn new(arch: Arch) -> Self { Self { arch } }

    /// Resolve a tensor name.
    pub fn name(&self, tensor: Tensor, suffix: Option<&str>, bid: i32, xid: i32) -> Result<String> {
        LlmTnImpl::new(self.arch, tensor, suffix, bid, xid).str()
    }
}

/// Fully resolved tensor name request.
pub struct LlmTnImpl {
    pub arch: Arch,
    pub tensor: Tensor,
    pub suffix: Option<String>,
    pub bid: i32,
    pub xid: i32,
}

impl LlmTnImpl {
    pub fn new(arch: Arch, tensor: Tensor, suffix: Option<&str>, bid: i32, xid: i32) -> Self {
        Self { arch, tensor, suffix: suffix.map(str::to_owned), bid, xid }
    }

    /// Format the tensor name.
    pub fn str(&self) -> Result<String> {
        let pattern = tensor_pattern(self.tensor).ok_or_else(|| {
            Error::new(format!("unknown tensor name for tensor {:?}", self.tensor))
        })?;
        let mut name = format_tensor(pattern, self.bid, self.xid);
        if let Some(suffix) = &self.suffix {
            name.push('.');
            name.push_str(suffix);
        }
        Ok(name)
    }
}

